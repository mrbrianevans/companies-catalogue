    provisions                               DOUBLE,
    net_assets                               DOUBLE,
    equity                                   DOUBLE,
    share_capital                            DOUBLE,
    retained_earnings                        DOUBLE,
    turnover                                 DOUBLE,
    gross_profit                             DOUBLE,
    operating_profit                         DOUBLE,
    profit_before_tax                        DOUBLE,
    tax_on_profit                            DOUBLE,
    profit_loss                              DOUBLE,
    staff_costs                              DOUBLE,
    software                                 VARCHAR,
    accountant_name                          VARCHAR,
    auditor_name                             VARCHAR,
    accounts_status                          VARCHAR,
    accounts_type                            VARCHAR,
    accounting_standard                      VARCHAR,
    dormant                                  BOOLEAN,
    trading_status                           VARCHAR,
    legal_form                               VARCHAR
