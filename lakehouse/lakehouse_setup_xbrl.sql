    zip_start                                DATE,
    zip_end                                  DATE,
    source_file                              VARCHAR NOT NULL,
    company_number                           VARCHAR,
    company_name                             VARCHAR,
    period_start                             DATE,
    period_end                               DATE,
    currency                                 VARCHAR,
    employees                                DOUBLE,
